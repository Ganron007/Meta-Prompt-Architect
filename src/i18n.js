function resolveLang(lang) {
  const code = String(lang || 'en').toLowerCase().split('-')[0];
  return SUPPORTED_LANGS.includes(code) ? code : 'en';
}

function getStrings(lang) {
  return STRINGS[resolveLang(lang)];
}

